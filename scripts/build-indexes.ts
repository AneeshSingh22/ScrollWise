/**
 * Validates every course day and custom topic, then writes the static import
 * lists the app bundles (lib/curriculum-data.ts, lib/topics-data.ts).
 *
 * Runs automatically before `npm run build`, `npm test` and `npm run dev`, so a
 * malformed or rule-breaking card can never reach Vercel. Run it by hand with:
 *
 *   npm run content
 *
 * Exits non-zero with a readable list of problems if anything fails.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";
import type { ZodType } from "zod";
import { DaySchema, lessonProblems, TopicSchema } from "../lib/schema";

const ROOT = join(__dirname, "..");
const CURRICULUM = join(ROOT, "data", "curriculum");
const TOPICS = join(ROOT, "data", "topics");

const problems: string[] = [];

function jsonFiles(dir: string): string[] {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith(".json"))
    .sort();
}

function load<T>(dir: string, file: string, schema: ZodType<T>): T | null {
  const where = `${basename(dir)}/${file}`;
  let raw: unknown;
  try {
    raw = JSON.parse(readFileSync(join(dir, file), "utf8"));
  } catch (e) {
    problems.push(`${where}: not valid JSON — ${(e as Error).message}`);
    return null;
  }
  const parsed = schema.safeParse(raw);
  if (!parsed.success) {
    for (const issue of parsed.error.issues) {
      problems.push(`${where}: ${issue.path.join(".") || "(root)"} — ${issue.message}`);
    }
    return null;
  }
  return parsed.data;
}

function checkLessons(where: string, lessons: { title: string; cards: Parameters<typeof lessonProblems>[0] }[]) {
  lessons.forEach((l, i) => {
    for (const p of lessonProblems(l.cards)) problems.push(`${where} lesson ${i + 1} "${l.title}": ${p}`);
  });
}

/** Writes a file only when its content changed, so git stays quiet. */
function writeIfChanged(path: string, content: string) {
  const old = existsSync(path) ? readFileSync(path, "utf8") : "";
  if (old !== content) writeFileSync(path, content);
}

// --- course days -------------------------------------------------------------
const dayFiles = jsonFiles(CURRICULUM);
const daySlugs = new Set<string>();
dayFiles.forEach((file, i) => {
  const day = load(CURRICULUM, file, DaySchema);
  if (!day) return;
  const expected = `day-${String(day.day).padStart(2, "0")}.json`;
  if (file !== expected) problems.push(`curriculum/${file}: holds day ${day.day}, so it should be named ${expected}`);
  if (day.day !== i + 1) problems.push(`curriculum/${file}: days must run 1, 2, 3… with no gaps`);
  daySlugs.add(day.slug);
  checkLessons(`curriculum/${file}`, day.lessons);
});

// --- custom topics -----------------------------------------------------------
const topicFiles = jsonFiles(TOPICS);
const topicSlugs = new Set<string>();
for (const file of topicFiles) {
  const topic = load(TOPICS, file, TopicSchema);
  if (!topic) continue;
  if (file !== `${topic.slug}.json`) problems.push(`topics/${file}: slug is "${topic.slug}", so the file must be ${topic.slug}.json`);
  if (daySlugs.has(topic.slug)) problems.push(`topics/${file}: slug "${topic.slug}" is already a course day`);
  if (topicSlugs.has(topic.slug)) problems.push(`topics/${file}: duplicate slug "${topic.slug}"`);
  topicSlugs.add(topic.slug);
  checkLessons(`topics/${file}`, topic.lessons);
}

if (problems.length) {
  console.error(`\n✗ Content check failed — ${problems.length} problem(s):\n`);
  for (const p of problems) console.error(`  • ${p}`);
  console.error("\nFix these, then run: npm run content\n");
  process.exit(1);
}

// --- write the import lists --------------------------------------------------
const ident = (s: string) => s.replace(/[^a-zA-Z0-9]/g, "_");

writeIfChanged(
  join(ROOT, "lib", "curriculum-data.ts"),
  [
    "// GENERATED by scripts/build-indexes.ts — do not edit. Run: npm run content",
    'import type { RawDay } from "./curriculum";',
    "",
    ...dayFiles.map((f) => `import ${ident(f.replace(".json", ""))} from "@/data/curriculum/${f}";`),
    "",
    "export const RAW_DAYS = [",
    ...dayFiles.map((f) => `  ${ident(f.replace(".json", ""))},`),
    "] as unknown as RawDay[];",
    "",
  ].join("\n"),
);

writeIfChanged(
  join(ROOT, "lib", "topics-data.ts"),
  [
    "// GENERATED by scripts/build-indexes.ts — do not edit. Run: npm run content",
    'import type { RawTopic } from "./curriculum";',
    "",
    ...topicFiles.map((f) => `import t_${ident(f.replace(".json", ""))} from "@/data/topics/${f}";`),
    "",
    "export const RAW_TOPICS = [",
    ...topicFiles.map((f) => `  t_${ident(f.replace(".json", ""))},`),
    "] as unknown as RawTopic[];",
    "",
  ].join("\n"),
);

console.log(`✓ Content OK — ${dayFiles.length} course days, ${topicFiles.length} custom topic(s).`);
